class LeadModel {
  final String date;
  final String name;
  final String contactNumber;
  final String country;
  final String leadStatus;
  final String programCategory;
  final String city;
  final String age;

  const LeadModel({
    required this.date,
    required this.name,
    required this.contactNumber,
    required this.country,
    required this.leadStatus,
    required this.programCategory,
    required this.city,
    required this.age,
  });
}